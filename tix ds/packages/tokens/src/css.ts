/**
 * Renders every token as a CSS custom property. This is the only place the
 * `--tds-*` naming convention is defined; components must never invent a variable
 * name that isn't emitted here.
 */

import {
  alpha,
  blue,
  green,
  magenta,
  neutral,
  orange,
  purple,
  red,
  turquoise,
  yellow,
} from "./primitives.js";
import { semanticDark, semanticLight, type SemanticColors } from "./semantic.js";
import { fontFamilyStack, fontWeight, typography } from "./typography.js";
import {
  elevation,
  focusRing,
  gradients,
  heroMotion,
  motion,
  platformDensity,
  radius,
  spacing,
} from "./layout.js";

const kebab = (value: string): string =>
  value.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();

const block = (selector: string, lines: string[]): string =>
  `${selector} {\n${lines.map((line) => `  ${line}`).join("\n")}\n}`;

const ramp = (name: string, values: Record<string, string>): string[] =>
  Object.entries(values).map(([step, hex]) => `--tds-color-${name}-${step}: ${hex};`);

const semanticVars = (colors: SemanticColors): string[] => [
  ...Object.entries(colors.background).map(
    ([key, value]) => `--tds-bg-${kebab(key)}: ${value};`,
  ),
  ...Object.entries(colors.text).map(([key, value]) => `--tds-text-${kebab(key)}: ${value};`),
  ...Object.entries(colors.icon).map(([key, value]) => `--tds-icon-${kebab(key)}: ${value};`),
  ...Object.entries(colors.stroke).map(
    ([key, value]) => `--tds-stroke-${kebab(key)}: ${value};`,
  ),
];

export function renderTokensCss(): string {
  const primitiveVars = [
    ...ramp("neutral", neutral),
    ...ramp("blue", blue),
    ...ramp("green", green),
    ...ramp("red", red),
    ...ramp("yellow", yellow),
    ...ramp("magenta", magenta),
    ...ramp("orange", orange),
    ...ramp("purple", purple),
    ...ramp("turquoise", turquoise),
    ...ramp("alpha", alpha),
  ];

  const scaleVars = [
    ...Object.entries(spacing).map(([step, value]) => `--tds-space-${step}: ${value}px;`),
    ...Object.entries(radius).map(([name, value]) => `--tds-radius-${name}: ${value}px;`),
    ...Object.entries(elevation).map(([name, value]) => `--tds-elevation-${name}: ${value};`),
    ...Object.entries(gradients).map(
      ([name, value]) => `--tds-gradient-${kebab(name)}: ${value.css};`,
    ),
  ];

  const typeVars = [
    `--tds-font-family: ${fontFamilyStack};`,
    ...Object.entries(fontWeight).map(
      ([name, value]) => `--tds-font-weight-${name}: ${value};`,
    ),
    ...Object.entries(typography).flatMap(([name, value]) => [
      `--tds-font-size-${kebab(name)}: ${value.fontSize}px;`,
      `--tds-line-height-${kebab(name)}: ${value.lineHeight}px;`,
      `--tds-font-weight-token-${kebab(name)}: ${value.fontWeight};`,
    ]),
  ];

  const motionVars = [
    ...Object.entries(motion.duration).map(
      ([name, value]) => `--tds-duration-${name}: ${value}ms;`,
    ),
    ...Object.entries(motion.easing).map(([name, value]) => `--tds-ease-${name}: ${value};`),
    // The hero's two moves, so a landing page can spend them without importing TS.
    `--tds-hero-settle-delay: ${heroMotion.settle.delay}ms;`,
    `--tds-hero-settle-duration: ${heroMotion.settle.duration}ms;`,
    `--tds-hero-settle-easing: ${heroMotion.settle.easing};`,
    `--tds-hero-settle-scale: ${heroMotion.settle.scaleFrom};`,
    `--tds-hero-stretch-max: ${heroMotion.stretch.maxPull}px;`,
    `--tds-hero-stretch-scale: ${heroMotion.stretch.scaleAtMaxPull};`,
    `--tds-hero-stretch-duration: ${heroMotion.stretch.duration}ms;`,
    `--tds-hero-stretch-easing: ${heroMotion.stretch.easing};`,
  ];

  const miscVars = [
    `--tds-focus-ring-width: ${focusRing.width}px;`,
    `--tds-focus-ring-offset: ${focusRing.offset}px;`,
  ];

  const platformBlocks = Object.entries(platformDensity).map(([name, density]) =>
    block(`[data-tds-platform="${name}"]`, [`--tds-min-target: ${density.minTarget}px;`]),
  );

  return [
    "/* Generated by @tiket-ds/tokens. Do not edit by hand — run `pnpm tokens:build`. */",
    "",
    block(":root", [
      ...primitiveVars,
      "",
      ...scaleVars,
      "",
      ...typeVars,
      "",
      ...motionVars,
      "",
      ...miscVars,
      "",
      `--tds-min-target: ${platformDensity.mobile.minTarget}px;`,
    ]),
    "",
    block(':root, [data-tds-theme="light"]', semanticVars(semanticLight)),
    "",
    block('[data-tds-theme="dark"]', semanticVars(semanticDark)),
    "",
    ...platformBlocks,
    "",
  ].join("\n");
}

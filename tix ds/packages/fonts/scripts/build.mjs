/**
 * Converts the Tiket Odyssey Text TTFs to woff2 and emits @font-face rules.
 *
 * The eight files carry three different `family` name records, so Figma treats them as
 * three families ("Tiket Odyssey Text", "… SemiBold", "… ExtraBold"). On the web that
 * is wrong: they are one family at four weights. This script is where that
 * normalization happens, and it is the reason `font-weight` is declared explicitly
 * rather than inferred from the file.
 */

import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

// wawoff2 is the WASM build of Google's woff2 encoder. The native `ttf2woff2` needs a
// compile step on install, which pnpm blocks by default — not worth the friction.
import { compress } from "wawoff2";

const here = dirname(fileURLToPath(import.meta.url));
const packageRoot = resolve(here, "..");
const workspaceRoot = resolve(packageRoot, "..", "..");

// The licensed TTFs live with the rest of the raw drop, next to `tds library/tds icon`.
const overrideDir = process.env.TDS_FONT_SOURCE_DIR;
const sourceDir = overrideDir ?? join(workspaceRoot, "tds library", "tds font");
const outDir = join(packageRoot, "dist");

// An override is a deliberate instruction to read a specific directory, so a typo in it
// should say so rather than quietly degrade to the fallback below.
if (overrideDir && !existsSync(overrideDir)) {
  process.stderr.write(`\nTDS_FONT_SOURCE_DIR does not exist: ${overrideDir}\n`);
  process.exit(1);
}

const FAMILY = "Tiket Odyssey Text";

/** [source file, css weight, css style] */
const FACES = [
  ["TiketOdysseyText-Regular.ttf", 400, "normal"],
  ["TiketOdysseyText-Italic.ttf", 400, "italic"],
  ["TiketOdysseyText-SemiBold.ttf", 600, "normal"],
  ["TiketOdysseyText-SemiBoldItalic.ttf", 600, "italic"],
  ["TiketOdysseyText-Bold.ttf", 700, "normal"],
  ["TiketOdysseyText-BoldItalic.ttf", 700, "italic"],
  ["TiketOdysseyText-ExtraBold.ttf", 800, "normal"],
  ["TiketOdysseyText-ExtraBoldItalic.ttf", 800, "italic"],
];

mkdirSync(outDir, { recursive: true });

const missing = [];
const rules = [];

for (const [file, weight, style] of FACES) {
  const sourcePath = join(sourceDir, file);
  if (!existsSync(sourcePath)) {
    missing.push(file);
    continue;
  }

  const ttf = readFileSync(sourcePath);
  const woff2 = Buffer.from(await compress(ttf));
  const outName = file.replace(/\.ttf$/, ".woff2");
  writeFileSync(join(outDir, outName), woff2);

  const saved = Math.round((1 - woff2.length / ttf.length) * 100);
  process.stdout.write(
    `  ${outName.padEnd(38)} ${String(Math.round(woff2.length / 1024)).padStart(3)} KB (-${saved}%)\n`,
  );

  rules.push(
    [
      "@font-face {",
      `  font-family: "${FAMILY}";`,
      `  src: url("./${outName}") format("woff2");`,
      `  font-weight: ${weight};`,
      `  font-style: ${style};`,
      "  font-display: swap;",
      "}",
    ].join("\n"),
  );
}

if (rules.length === 0) {
  // The proprietary TTFs are deliberately not committed (see README), so every
  // environment that isn't a machine with the design system asset drop — CI, Vercel, a
  // stakeholder's clone — lands here. That is expected, not an error: `--tds-font-family`
  // already carries a system-font fallback, so the site still renders correctly, just in
  // a stand-in typeface. Failing the whole build over a licensed asset that was never
  // supposed to be in the repository would block every deployment not run by hand.
  const fallback = [
    "/*",
    " * Generated by @tiket-ds/fonts.",
    " *",
    " * Tiket Odyssey Text is proprietary and its source TTFs were not found in",
    ` * ${sourceDir}. No @font-face rules were emitted — the design system's`,
    ' * `--tds-font-family` token already falls back to the system font stack, so this',
    " * is a visual difference (a stand-in sans-serif), not a broken build. Run",
    " * `pnpm fonts:build` on a machine with the asset drop to embed the real typeface.",
    " */",
    "",
  ].join("\n");
  writeFileSync(join(outDir, "fonts.css"), fallback, "utf8");
  process.stdout.write(
    `@tiket-ds/fonts: no source TTFs in ${sourceDir}; shipping the system-font fallback ` +
      "instead of Tiket Odyssey Text. See packages/fonts/README.md.\n",
  );
  process.exit(0);
}

// Some faces present and some not is the one case worth shouting about: it renders the
// family in two different typefaces, which reads as a styling bug rather than a missing
// asset drop. Still not fatal — the faces that are here are correct.
if (missing.length > 0) {
  process.stderr.write(
    `\nMissing ${missing.length} of ${FACES.length} font file(s) in ${sourceDir}:\n` +
      missing.map((file) => `  - ${file}`).join("\n") +
      "\nSee packages/fonts/README.md. Set TDS_FONT_SOURCE_DIR to point elsewhere.\n",
  );
}

const header = [
  "/*",
  " * Generated by @tiket-ds/fonts. Do not edit by hand — run `pnpm fonts:build`.",
  " *",
  ` * All faces collapse into one CSS family, "${FAMILY}", differentiated by weight and`,
  " * style. There is no Light (300) or Medium (500) weight — do not reference one.",
  " */",
].join("\n");

writeFileSync(join(outDir, "fonts.css"), `${header}\n\n${rules.join("\n\n")}\n`, "utf8");
process.stdout.write(`@tiket-ds/fonts: wrote ${rules.length} faces to ${outDir}/fonts.css\n`);
